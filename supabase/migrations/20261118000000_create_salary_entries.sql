create table if not exists public.salary_entries (
  id bigint generated by default as identity primary key,
  role text not null check (char_length(btrim(role)) between 1 and 120),
  company_location text not null check (char_length(btrim(company_location)) between 1 and 120),
  monthly_gross_salary numeric(12, 2) not null check (monthly_gross_salary > 0),
  salary_gross_in_usd numeric(12, 2) check (salary_gross_in_usd is null or salary_gross_in_usd >= 0),
  years_of_experience text,
  degree text,
  company_size text,
  country_location text,
  nationality text,
  industry text,
  currency text not null default 'ZMW' check (char_length(btrim(currency)) between 3 and 8),
  submission_date date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.salary_entries enable row level security;

drop policy if exists "Anyone can read salary entries" on public.salary_entries;
create policy "Anyone can read salary entries"
  on public.salary_entries for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit salary entries" on public.salary_entries;
create policy "Anyone can submit salary entries"
  on public.salary_entries for insert
  to anon, authenticated
  with check (
    char_length(btrim(role)) between 1 and 120
    and char_length(btrim(company_location)) between 1 and 120
    and monthly_gross_salary > 0
  );

grant select, insert on public.salary_entries to anon, authenticated;
grant usage, select on sequence public.salary_entries_id_seq to anon, authenticated;
